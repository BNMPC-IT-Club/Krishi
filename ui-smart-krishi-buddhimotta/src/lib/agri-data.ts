const hash = (value: string) => Array.from(value).reduce((sum, item) => sum + item.charCodeAt(0), 0);

export function createPriceHistory(crop: string, district: string) {
  const base = priceBaselines[crop] ?? 50;
  const seed = hash(crop + district);
  return Array.from({ length: 14 }, (_, index) => {
    const weekly = Math.sin((index + (seed % 9)) * 0.72) * 2.1;
    const gradual = index * (((seed % 5) - 2) * 0.14);
    const localDifference = (seed % 13) - 6;
    const price = Math.max(12, Math.round((base + localDifference + weekly + gradual) * 10) / 10);
    return { day: `${String(index + 8).padStart(2, "0")}/০৩`, price };
  });
}

export function createForecast(crop: string, district: string) {
  const history = createPriceHistory(crop, district);
  const last = history.at(-1)?.price ?? 50;
  const seed = hash(district + crop);
  const direction = ((seed % 7) - 3) * 0.32;
  return Array.from({ length: 14 }, (_, index) => {
    const price = Math.max(12, Math.round((last + direction * (index + 1) + Math.sin(index * 1.37) * 0.8) * 10) / 10);
    return { day: `${String(index + 22).padStart(2, "0")}/০৩`, price };
  });
}

